export function nextKey(p) {
  p.seq = (p.seq || 200) + 1;
  return p.key + '-' + p.seq;
}
export function createTask(f) {
  const p = proj(f.project) || visibleProjects().find(canSee);
  const maxO = Math.max(0, ...D().tasks.map(t => t.order));
  const t = Object.assign(
    {
      project: p.id,
      title: 'Sin título',
      status: 'todo',
      assignee: SINGLE_USER ? D().me : null,
      priority: 'none',
      due: null,
      start: null,
      labels: [],
      subtasks: [],
      attachments: [],
      deps: [],
      desc: '',
      estimate: null,
      created: Date.now(),
      updated: Date.now(),
      order: maxO + 1,
      fav: false,
      recur: null,
    },
    f,
    { project: p.id },
  );
  t.id = f.id || uid('t');
  t.key = f.key || nextKey(p);
  D().tasks.push(t);
  fxSet({ added: t.id });
  logAct('creó', t);
  return t;
}
export const RECUR_DAYS = { Diaria: 1, Semanal: 7, 'Cada 2 semanas': 14, Mensual: 30 };
export function applyPatch(t, patch) {
  const msgs = [];
  for (const k of Object.keys(patch)) {
    const old = t[k],
      nv = patch[k];
    if (JSON.stringify(old) === JSON.stringify(nv)) continue;
    t[k] = nv;
    if (k === 'status') {
      if (nv === 'done') {
        t.completedAt = Date.now();
        t.prevStatus = old;
        logAct('completó', t);
        fxSet({ done: t.id });
      } else logAct('movió', t, `de ${ST[old].name} a ${ST[nv].name}`);
      if (nv === 'done' && t.recur && t.due) {
        const nd = iso(addD(parse(t.due), RECUR_DAYS[t.recur] || 7));
        const n = createTask({
          ...JSON.parse(JSON.stringify(t)),
          id: undefined,
          key: undefined,
          status: 'todo',
          due: nd,
          start: nd,
          subtasks: t.subtasks.map(s => ({ ...s, done: false })),
          completedAt: null,
          attachments: [],
        });
        delete n.prevStatus;
        msgs.push(`Siguiente “${t.title}” programada para el ${fmtDate(nd)}`);
      }
    } else if (k === 'assignee') logAct('asignó', t, nv ? `a ${mem(nv)?.name}` : '(sin asignar)');
    else if (k === 'priority') logAct('cambió prioridad de', t, `a ${PR[nv].name}`);
    else if (k === 'due') logAct('cambió fecha límite de', t, nv ? `a ${fmtDate(nv)}` : '(eliminada)');
    else if (k === 'start') logAct('cambió fecha inicio de', t, nv ? `a ${fmtDate(nv)}` : '(eliminada)');
    else if (k === 'project') {
      const p = proj(nv);
      t.key = nextKey(p);
      logAct('movió', t, `al proyecto ${p.name}`);
    } else if (k === 'labels') logAct('actualizó etiquetas en', t);
    else if (k === 'title') logAct('renombró', t, `a “${nv}”`);
    else if (k === 'recur') logAct('configuró repetición en', t, nv ? nv.toLowerCase() : 'desactivada');
    else if (k === 'estimate') logAct('estimó', t, nv || 'ninguna');
    else if (k === 'deps') logAct('actualizó dependencias de', t);
    t.updated = Date.now();
  }
  return msgs;
}
export function updateTask(id, patch) {
  if (id === '__form') {
    Object.assign(S.ui.form, patch);
    render();
    return;
  }
  const t = task(id);
  if (!t) return;
  let msgs = [];
  if (
    mutate(() => {
      msgs = applyPatch(t, patch);
    })
  )
    msgs.forEach(m => toast(m, { kind: 'info' }));
}
