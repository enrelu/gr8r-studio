export async function copy(text, msg = 'Enlace copiado') {
  try {
    await navigator.clipboard.writeText(text);
    toast(msg);
  } catch {
    toast('No se puede copiar aquí — ' + text, { kind: 'info', ms: 6000 });
  }
}
